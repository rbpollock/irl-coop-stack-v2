#!/usr/bin/env python3
"""Firewall generator — extracts ALL backend ports from app proxy specs.

Traefik (in Docker) reverse-proxies to ALL ports listed in app proxy configs,
whether the app is a container (type: image) or host process (type: source).
For containers the INPUT rule is harmless; for host processes it is essential.
"""
import sys, os, glob, yaml

def main(instance):
    root = os.path.dirname(os.path.dirname(os.path.dirname(__file__)))
    apps_dir = os.path.join(root, "infra", "instances", instance, "apps")
    out_dir = os.path.join(root, "infra", "out", instance)
    os.makedirs(out_dir, exist_ok=True)

    ports = set()
    for spec_path in sorted(glob.glob(os.path.join(apps_dir, "*.yaml"))):
        with open(spec_path) as f:
            spec = yaml.safe_load(f) or {}

        # Skip disabled apps
        if spec.get("enabled") is False:
            continue

        # Extract proxy port (dict form)
        proxy = spec.get("proxy", {})
        if isinstance(proxy, dict):
            p = proxy.get("port")
            if isinstance(p, int):
                ports.add(p)
        elif isinstance(proxy, list):
            for entry in proxy:
                p = entry.get("port")
                if isinstance(p, int):
                    ports.add(p)

        # Extract routes ports (Traefik apex routes)
        for route in spec.get("routes", []):
            p = route.get("port")
            if isinstance(p, int):
                ports.add(p)

    port_list = ", ".join(str(p) for p in sorted(ports))

    nft = f"""#!/usr/sbin/nft -f
# Auto-generated by generate-firewall.py for instance '{instance}'.
# Do NOT hand-edit — change apps/*.yaml specs and rerun instead.

define backend_ports = {{ {port_list} }}

include "{root}/infra/instances/{instance}/firewall.nft"
"""
    out_path = os.path.join(out_dir, "firewall.nft")
    with open(out_path, "w") as f:
        f.write(nft)
    print(f"Generated {out_path}")
    print(f"  Backend ports: {{ {port_list} }}")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "dev")
